"""Map the existing glass button artwork onto a smooth shoulder mesh."""
from pathlib import Path
import math


def outline(points, trims):
    starts, ends = [], []
    for i, p in enumerate(points):
        def toward(q):
            length = math.dist(p, q)
            return tuple(p[j] + (q[j] - p[j]) * trims[i] / length for j in range(2))
        starts.append(toward(points[i - 1]))
        ends.append(toward(points[(i + 1) % 4]))
    result = []
    for i, p in enumerate(points):
        for step in range(8):
            t = step / 8
            result.append(tuple((1-t)**2 * starts[i][j] + 2*t*(1-t)*p[j] + t*t*ends[i][j] for j in range(2)))
        for step in range(8):
            t = step / 8
            result.append(tuple((1-t)*ends[i][j] + t*starts[(i+1) % 4][j] for j in range(2)))
    return result


def inset(points, width):
    lines = []
    for i, p in enumerate(points):
        q = points[(i+1) % 4]
        dx, dy = q[0]-p[0], q[1]-p[1]
        length = math.hypot(dx, dy)
        lines.append(((p[0]-dy*width/length, p[1]+dx*width/length), (dx, dy)))
    result = []
    for i in range(4):
        p, a = lines[i-1]
        q, b = lines[i]
        t = ((q[0]-p[0])*b[1] - (q[1]-p[1])*b[0]) / (a[0]*b[1]-a[1]*b[0])
        result.append((p[0]+t*a[0], p[1]+t*a[1]))
    return result


def generate():
    points = [(370., 15.390041), (390.9, 17.9), (392., 24.609959), (370., 24.609959)]
    outer = outline(points, [2.5, 2.5, 2., 2.])[::2]
    inner = outline(inset(points, 1.5), [1., 1., .5, .5])[::2]
    center = (381., 20.)
    # Sample the rim in the direction of its outward normal. This keeps the
    # highlight above the shoulder instead of stretching it toward a corner.
    rim_uv = []
    for i, p in enumerate(outer):
        previous, following = outer[(i-1) % 32], outer[(i+1) % 32]
        dx, dy = following[0]-previous[0], following[1]-previous[1]
        length = math.hypot(dx, dy)
        nx, ny = dy/length, -dx/length
        # The outermost atlas pixels are transparent; start inside that gutter
        # so the sloped top edge retains the same bevel as the round buttons.
        rim_uv.append(((66.5+18.5*.92*nx)/512., 1.-(19.+19.*.92*ny)/256.))
    # The glass uses the atlas's clean vertical center, so its light stays
    # horizontal across the entire face rather than curving around a fan.
    def glass_uv(p):
        t = max(0., min(1., (p[1]-15.390041)/9.219918))
        return (66.5/512., 1.-(8.+22.*t)/256.)
    patches, uvs = [], []
    for i in range(32):
        j = (i+1) % 32
        patches.append((*outer[i], *outer[j], *inner[i], *inner[j]))
        def inner_rim(uv):
            return (66.5/512.+(uv[0]-66.5/512.)*(.76/.92), 1.-19./256.+(uv[1]-(1.-19./256.))*(.76/.92))
        uvs.append((*rim_uv[i], *rim_uv[j], *inner_rim(rim_uv[i]), *inner_rim(rim_uv[j])))
    for i in range(32):
        j = (i+1) % 32
        patches.append((*inner[i], *inner[j], *center, *center))
        uvs.append((*glass_uv(inner[i]), *glass_uv(inner[j]), *glass_uv(center), *glass_uv(center)))
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '#ifndef RETUNED_MANUAL_JUMP_HUD_H', '#define RETUNED_MANUAL_JUMP_HUD_H',
             '/* Generated by generate_jump_shoulder.py: bevel rim and top-lit glass. */']
    # Reflect the same mesh for the opposite shoulder. Reverse each strip's
    # pairs to retain its winding; matching UV pairs keep the light above.
    order = (1, 0, 3, 2)
    left_patches = [tuple(value for v in order for value in
                         (762.-row[v*2], row[v*2+1])) for row in patches]
    left_uvs = [tuple(value for v in order for value in row[v*2:v*2+2]) for row in uvs]
    for name, values in [('ManualJump_BumperPatches', patches), ('ManualJump_BumperUVs', uvs),
                         ('ManualJump_LeftBumperPatches', left_patches), ('ManualJump_LeftBumperUVs', left_uvs)]:
        lines.append('static const float '+name+'[64][8]={')
        for row in values:
            lines.append(' {'+', '.join(f'{v:.9f}f' for v in row)+'},')
        lines.append('};')
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    Path(__file__).with_name('manual_jump_hud.h').write_text(generate())
