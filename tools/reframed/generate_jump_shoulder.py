"""Generate a smooth, hollow shoulder outline with 64 connected patches."""
from pathlib import Path
import math


def outline(points, trims):
    starts, ends = [], []
    for i, p in enumerate(points):
        def toward(q):
            length = math.dist(p, q)
            return tuple(p[j] + (q[j] - p[j]) * trims[i] / length for j in range(2))
        starts.append(toward(points[i - 1]))
        ends.append(toward(points[(i + 1) % 4]))
    result = []
    for i, p in enumerate(points):
        for step in range(8):
            t = step / 8
            result.append(tuple((1-t)**2 * starts[i][j] + 2*t*(1-t)*p[j] + t*t*ends[i][j] for j in range(2)))
        for step in range(8):
            t = step / 8
            result.append(tuple((1-t)*ends[i][j] + t*starts[(i+1) % 4][j] for j in range(2)))
    return result


def inset(points, width):
    lines = []
    for i, p in enumerate(points):
        q = points[(i+1) % 4]
        dx, dy = q[0]-p[0], q[1]-p[1]
        length = math.hypot(dx, dy)
        lines.append(((p[0]-dy*width/length, p[1]+dx*width/length), (dx, dy)))
    result = []
    for i in range(4):
        p, a = lines[i-1]
        q, b = lines[i]
        t = ((q[0]-p[0])*b[1] - (q[1]-p[1])*b[0]) / (a[0]*b[1]-a[1]*b[0])
        result.append((p[0]+t*a[0], p[1]+t*a[1]))
    return result


def generate():
    points = [(370., 15.390041), (390.9, 17.9), (392., 24.609959), (370., 24.609959)]
    outer = outline(points, [1., 2., 1., 1.])
    inner = outline(inset(points, .5), [.5, 1.5, .5, .5])
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '#ifndef RETUNED_MANUAL_JUMP_HUD_H', '#define RETUNED_MANUAL_JUMP_HUD_H',
             '/* ReMasked-style shoulder, with straight edges and rounded corners.',
             ' * Generated by generate_jump_shoulder.py; transparent interior. */',
             'static const float ManualJump_BumperPatches[64][8]={']
    for i in range(64):
        j = (i+1) % 64
        values = (*outer[i], *outer[j], *inner[i], *inner[j])
        lines.append(' {' + ', '.join(f'{v:.6f}f' for v in values) + '},')
    return '\n'.join(lines + ['};', '#endif', ''])


if __name__ == '__main__':
    Path(__file__).with_name('manual_jump_hud.h').write_text(generate())
